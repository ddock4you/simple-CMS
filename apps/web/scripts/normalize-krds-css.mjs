import { createRequire } from 'node:module';
import { cpSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));

const krdsUiuxRoot = dirname(require.resolve('krds-uiux/package.json'));
const outputPath = resolve(__dirname, '../app/krds-normalized.css');
const legacyPublicImagePath = resolve(__dirname, '../public/krds');
const publicImagePath = resolve(__dirname, '../public/assets/krds/img');

const cssFiles = [
  'resources/css/token/krds_tokens.css',
  'resources/css/common/common.css',
  'resources/css/component/component.css',
];

const REM_SCALE = 0.625;

function formatNumber(value) {
  return Number(value.toFixed(6)).toString();
}

const source = cssFiles
  .map((file) => readFileSync(resolve(krdsUiuxRoot, file), 'utf8'))
  .join('\n');

let normalized = source
  .replace(/@charset\s+["'][^"']+["'];\s*/g, '')
  .replace(/@import\s+["']\.\.\/\.\.\/css\/token\/krds_tokens\.css["'];?\s*/g, '')
  .replace(
    /url\((['"]?)(?:\.\.\/)+img\/(?:img\/)?([^'")]+)\1\)/g,
    'url(/assets/krds/img/$2)',
  )
  .replace(/--krds-font-size-base:\s*62\.5%/g, '--krds-font-size-base: 100%')
  .replace(/(-?\d*\.?\d+)rem\b/g, (_, rawValue) => {
    const value = Number.parseFloat(rawValue);

    if (!Number.isFinite(value) || value === 0) {
      return `${rawValue}rem`;
    }

    return `${formatNumber(value * REM_SCALE)}rem`;
  });

const banner = `/*
 * This file is generated by scripts/normalize-krds-css.mjs.
 * Do not edit by hand.
 *
 * Generated from krds-uiux token/common/component CSS, not krds-react's bundled
 * reset-heavy CSS. KRDS ships with html { font-size: 62.5%; } and rem values
 * authored against a 10px root. The web app keeps the browser/Tailwind standard
 * 16px root, so this generated copy changes the root token to 100% and scales
 * KRDS rem values by 0.625 to preserve the same visual pixel sizes for KRDS
 * components.
 */\n`;

const leftoverImport = normalized.match(/@import\s+[^;]+;/);
if (leftoverImport) {
  throw new Error(
    `Unexpected @import left in generated KRDS CSS: ${leftoverImport[0]}`,
  );
}

rmSync(legacyPublicImagePath, { recursive: true, force: true });
rmSync(publicImagePath, { recursive: true, force: true });
cpSync(resolve(krdsUiuxRoot, 'resources/img'), publicImagePath, {
  recursive: true,
});

writeFileSync(
  outputPath,
  `@charset "UTF-8";\n${banner}@layer krds-base {\n${normalized}\n}\n`,
);

console.log(`Generated ${outputPath}`);
