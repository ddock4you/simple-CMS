import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));

const sourcePath = require.resolve('krds-react/dist/index.css');
const outputPath = resolve(__dirname, '../app/krds-normalized.css');
const source = readFileSync(sourcePath, 'utf8');

const REM_SCALE = 0.625;

function formatNumber(value) {
  return Number(value.toFixed(6)).toString();
}

let normalized = source
  .replace(/--krds-font-size-base:\s*62\.5%/g, '--krds-font-size-base: 100%')
  .replace(/(-?\d*\.?\d+)rem\b/g, (_, rawValue) => {
    const value = Number.parseFloat(rawValue);

    if (!Number.isFinite(value) || value === 0) {
      return `${rawValue}rem`;
    }

    return `${formatNumber(value * REM_SCALE)}rem`;
  });

const banner = `/*
 * This file is generated by scripts/normalize-krds-css.mjs.
 * Do not edit by hand.
 *
 * KRDS ships with html { font-size: 62.5%; } and rem values authored against
 * a 10px root. The web app keeps the browser/Tailwind standard 16px root, so
 * this generated copy changes the root token to 100% and scales KRDS rem values
 * by 0.625 to preserve the same visual pixel sizes for KRDS components.
 */\n`;

const charsetMatch = normalized.match(/^@charset\s+"[^"]+";/);

if (charsetMatch) {
  normalized = normalized.slice(charsetMatch[0].length);
  writeFileSync(outputPath, `${charsetMatch[0]}\n${banner}${normalized}`);
} else {
  writeFileSync(outputPath, `${banner}${normalized}`);
}

console.log(`Generated ${outputPath}`);
